def _esc(text: str) -> str:
    """HTML-escape a string."""
    return (text.replace("&", "&amp;").replace("<", "&lt;")
                .replace(">", "&gt;").replace('"', "&quot;"))


def _get_triage_guidance(chain) -> list[tuple[str, str, str]]:
    """Generate real-vs-informational triage questions per chain category.

    Returns list of (question, if_yes, if_no) tuples.
    """
    cat = chain.category.lower()

    if cat == "credential_exposure":
        return [
            ("Does the secret look like a real key/token (not a placeholder)?",
             "**Likely real** — validate against the service",
             "Probably a template/example — **informational**"),
            ("Can you authenticate to a service with it?",
             "**Confirmed exploitable** — report as HIGH/CRITICAL",
             "Key might be revoked/expired — lower severity"),
            ("Does the key have write/admin permissions?",
             "**Critical** — full account compromise",
             "Read-only access — still report but lower impact"),
            ("Is the secret in a production JS bundle (not test/staging)?",
             "**Production exposure** — needs immediate rotation",
             "Test environment — still report but note the scope"),
        ]
    elif cat == "takeover":
        return [
            ("Does the CNAME still resolve to a claimable service?",
             "**Exploitable** — you can claim and serve content",
             "CNAME removed or reclaimed — **false positive**"),
            ("Can you actually register the service?",
             "**Confirmed** — demonstrate with benign PoC page",
             "Service requires org verification — lower confidence"),
            ("Does the parent domain set cookies on this subdomain?",
             "**Session hijack risk** — escalate to CRITICAL",
             "No cookie scope — still HIGH for phishing"),
        ]
    elif cat == "data_exfil":
        return [
            ("Can you connect without authentication?",
             "**Confirmed** — unauthenticated access to data",
             "Auth required — still report exposed port as MEDIUM"),
            ("Does the service contain sensitive data?",
             "**Critical** — PII/credentials exposed",
             "Empty/test data — lower to informational"),
            ("Is the port accessible from the internet (not just LAN)?",
             "**Internet-exposed** — report as HIGH+",
             "Internal only — note in report, lower severity"),
        ]
    elif cat in ("rce", "vulnerability"):
        return [
            ("Did the PoC command produce the expected output?",
             "**Confirmed RCE/vuln** — report immediately",
             "Patched or mitigated — try alternate payloads"),
            ("Is the target running the vulnerable version?",
             "**Version match** — high likelihood of exploitation",
             "Different version — may be patched, test anyway"),
            ("Can you demonstrate impact (file read, command exec)?",
             "**Full proof** — include output in report",
             "Blind/time-based only — still valid but note limitations"),
        ]
    elif "cors" in cat or "auth" in cat:
        return [
            ("Does the CORS response include credentials: true?",
             "**Exploitable** — cross-origin credential theft possible",
             "No credentials header — limited impact, note as info"),
            ("Does the endpoint return sensitive data?",
             "**Real impact** — user data can be exfiltrated",
             "Public data only — **informational**"),
        ]
    else:
        return [
            ("Can you reproduce the finding manually?",
             "**Confirmed** — document reproduction steps",
             "Might be scanner noise — **verify before reporting**"),
            ("Does exploiting this give unauthorized access or data?",
             "**Real vulnerability** — determine severity by impact",
             "No clear impact — classify as **informational**"),
            ("Would a reasonable developer consider this a bug?",
             "**Report it** — include suggested remediation",
             "Likely intended behavior — skip or note as low"),
        ]
