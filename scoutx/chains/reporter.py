"""Attack Chain Report Generators — MD, HTML, and JSON output.

Turns ChainReport objects into beautiful, actionable documents
that a penetration tester can follow step by step.
"""
from __future__ import annotations

import json
import logging
from datetime import datetime, timezone
from pathlib import Path

from scoutx.chains.models import ChainReport, ChecklistItem

logger = logging.getLogger("scoutx.chains.reporter")


class ChainReporter:
    """Generate attack chain reports in multiple formats."""

    def __init__(self, report: ChainReport) -> None:
        self._report = report

    def write_all(self, output_dir: Path) -> list[Path]:
        """Write all report formats to the output directory."""
        output_dir.mkdir(parents=True, exist_ok=True)
        paths = []
        paths.append(self.write_markdown(output_dir / "attack_playbook.md"))
        paths.append(self.write_json(output_dir / "attack_chains.json"))
        paths.append(self.write_html(output_dir / "attack_playbook.html"))
        paths.append(self.write_checklist(output_dir / "vuln_checklist.md"))
        return paths

    # ------------------------------------------------------------------
    # Markdown
    # ------------------------------------------------------------------
    def write_markdown(self, path: Path) -> Path:
        """Write a detailed, actionable attack playbook for pentesters."""
        r = self._report
        lines: list[str] = []
        sev = r.severity_counts()
        ts = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")

        lines.append(f"# 🎯 Attack Playbook: {r.target}")
        lines.append(f"\n> Generated by ScoutX Attack Chain Engine | {ts}")
        lines.append("> **PURPOSE:** Test each finding below to confirm if it's a real, exploitable vulnerability")
        lines.append("> before including it in your report. Follow the validation steps — don't submit informational noise.")
        lines.append("\n## Dashboard\n")
        lines.append("| Metric | Value |")
        lines.append("|--------|-------|")
        lines.append(f"| Total Attack Chains | **{len(r.chains)}** |")
        lines.append(f"| 🔴 Critical | {sev.get('critical', 0)} |")
        lines.append(f"| 🟠 High | {sev.get('high', 0)} |")
        lines.append(f"| 🟡 Medium | {sev.get('medium', 0)} |")
        lines.append(f"| 🟢 Low / Info | {sev.get('low', 0)} |")
        lines.append(f"| Checklist Coverage | {len(r.applicable_checks)}/{len(r.checklist)} applicable |")

        if r.chains:
            lines.append("\n---\n")
            lines.append("## Attack Chains\n")

        for i, chain in enumerate(r.chains, 1):
            sev_emoji = {"critical": "🔴", "high": "🟠", "medium": "🟡", "low": "🟢"}.get(chain.severity, "⚪")
            lines.append(f"### {sev_emoji} Chain #{i}: [{chain.severity.upper()}] {chain.title}")
            lines.append("\n| Field | Value |")
            lines.append("|-------|-------|")
            lines.append(f"| Confidence | **{chain.confidence:.0%}** |")
            lines.append(f"| Category | {chain.category} |")
            if chain.cvss_score:
                lines.append(f"| CVSS | {chain.cvss_score} |")
            if chain.target_host:
                lines.append(f"| Target | `{chain.target_host}` |")

            lines.append("\n#### What Is This?")
            lines.append(f"\n{chain.description}")

            if chain.affected_assets:
                lines.append("\n#### Affected Assets")
                for a in chain.affected_assets[:10]:
                    lines.append(f"- `{a}`")

            if chain.prerequisites:
                lines.append("\n#### Prerequisites (What must be true)")
                for p in chain.prerequisites:
                    lines.append(f"- {p}")

            # The meat — step by step exploitation
            lines.append("\n#### 🔬 Step-by-Step Exploitation & Validation\n")
            lines.append("> Follow these steps IN ORDER. Each step builds on the previous one.")
            lines.append("> If any step fails, the chain is likely **not exploitable** — mark as informational.\n")

            for step in chain.steps:
                lines.append(f"**Step {step.order}: {step.action}**\n")
                lines.append("```bash")
                lines.append(f"{step.command}")
                lines.append("```\n")
                lines.append(f"✅ **Expected if vulnerable:** {step.expected_result}")
                if step.notes:
                    lines.append(f"\n💡 **Note:** {step.notes}")
                lines.append("")

            # Is this real?
            lines.append("#### ⚖️ Is This Real or Informational?\n")
            _triage = _get_triage_guidance(chain)
            lines.append("| Question | If YES → | If NO → |")
            lines.append("|----------|----------|---------|")
            for q, yes, no in _triage:
                lines.append(f"| {q} | {yes} | {no} |")

            # Before you submit
            lines.append("\n#### 📋 Before You Submit\n")
            lines.append("- [ ] Completed all validation steps above")
            lines.append("- [ ] Captured screenshots/responses as evidence")
            lines.append("- [ ] Confirmed this is **not** a false positive")
            lines.append("- [ ] Impact is clear (what can an attacker DO with this?)")
            lines.append("- [ ] Wrote reproduction steps someone else can follow")

            if chain.mitigation:
                lines.append("\n#### 🛡️ Remediation\n")
                lines.append(f"{chain.mitigation}")

            if chain.tools_needed:
                lines.append(f"\n**Tools needed:** `{', '.join(chain.tools_needed)}`")

            if chain.references:
                lines.append("\n#### References")
                for ref in chain.references:
                    lines.append(f"- {ref}")
            lines.append("\n---\n")

        path.write_text("\n".join(lines), encoding="utf-8")
        logger.info("Markdown playbook written to %s", path)
        return path

    # ------------------------------------------------------------------
    # JSON
    # ------------------------------------------------------------------
    def write_json(self, path: Path) -> Path:
        """Write JSON report."""
        data = self._report.to_dict()
        path.write_text(json.dumps(data, indent=2, default=str), encoding="utf-8")
        logger.info("JSON report written to %s", path)
        return path

    # ------------------------------------------------------------------
    # Checklist Markdown
    # ------------------------------------------------------------------
    def write_checklist(self, path: Path) -> Path:
        """Write the vulnerability checklist as markdown."""
        r = self._report
        lines: list[str] = []
        lines.append(f"# Vulnerability Checklist: {r.target}")
        lines.append(f"\n> {len(r.applicable_checks)}/{len(r.checklist)} checks applicable based on recon findings\n")

        # Group by phase
        phases: dict[str, list[ChecklistItem]] = {}
        for item in r.checklist:
            if item.phase not in phases:
                phases[item.phase] = []
            phases[item.phase].append(item)

        for phase, items in phases.items():
            applicable = [i for i in items if i.applicable]
            lines.append(f"## {phase} ({len(applicable)}/{len(items)} applicable)")
            lines.append("")
            for item in items:
                mark = "x" if item.applicable else " "
                sev_tag = f"[{item.severity.upper()[0]}]"
                lines.append(f"- [{mark}] {sev_tag} {item.check}")
                if item.applicable and item.reason:
                    lines.append(f"  - *{item.reason}*")
            lines.append("")

        path.write_text("\n".join(lines), encoding="utf-8")
        logger.info("Checklist written to %s", path)
        return path

    # ------------------------------------------------------------------
    # HTML
    # ------------------------------------------------------------------
